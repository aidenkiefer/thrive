/**
 * Renders the seed plan as one SQL transaction of upserts, applied through the
 * Supabase MCP instead of the service-role script (#101, owner choice b).
 * Rows travel as one JSON literal per table and Postgres casts each value to
 * its column type (jsonb_populate_record), so no value is spliced into SQL.
 * Same writes as scripts/seed-current.ts: upsert on the natural key, never delete.
 * Publishable rows go in as drafts (the database refuses an INSERT with
 * published_at, #94) and are then published through cms_set_published as the
 * `seed` system actor, keeping their original publish time.
 */
import { SEED_TABLES, type Row, type SeedPlan, type SeedTable } from './plan'

/**
 * The generated file, committed next to batch A. It replaces 2026-11-19-seed.sql,
 * which was applied before the INSERT guard and is now refused by it (#94).
 */
export const SEED_SQL = 'supabase/ops/2026-11-20-seed.sql'

export const SEED_SQL_HEADER = `
-- =============================================================================
-- Seed for #101 (publishing as the seed actor, #94), generated by
-- scripts/seed-sql.ts from migration-files/parsed/.
-- Do not edit by hand: regenerate, and src/lib/seed/sql.test.ts fails if stale.
--
-- Run after 2026-11-19-batch-a.sql and 20261120000000_system_actors.sql. One
-- transaction: upserts drafts on slug (and on recurring_event_id +
-- start_datetime for occurrences), never deletes, then publishes each dated row
-- through cms_set_published as the seed system actor with its original publish
-- time. A row that is already published, or whose publish state was already
-- changed through cms_set_published (a staff unpublish), is left as it is.
-- Refuses while a planned event slug is published in the other event table,
-- or without an active seed actor.
-- Verify: \`npm run seed -- --dry-run\` reports 0 to insert and 0 to update.
-- =============================================================================`

const TAG = '$seed$'
const IDENT = /^[a-z_]+$/

/** Plan columns holding a slug, written as the id of the row with that slug. */
const FOREIGN: Partial<Record<SeedTable, Record<string, [column: string, table: SeedTable]>>> = {
  sermons: { speaker_slug: ['speaker_id', 'speakers'], series_slug: ['series_id', 'sermon_series'] },
  event_occurrences: { recurring_slug: ['recurring_event_id', 'recurring_events'] },
}

/** cms_set_published entity type for each publishable seed table. */
export const PUBLISH_AS: Partial<Record<SeedTable, string>> = {
  sermon_series: 'sermon_series', sermons: 'sermon', recurring_events: 'recurring_event', one_time_events: 'one_time_event',
}

/** The reserved `seed` system actor (supabase/migrations/20261120000000_system_actors.sql). */
const SEED_ACTOR = `select actor_id from admin_staff_accounts where kind = 'system' and name = 'seed' and status = 'active'`

const CONFLICT: Record<SeedTable, string[]> = {
  speakers: ['slug'], sermon_series: ['slug'], sermons: ['slug'],
  recurring_events: ['slug'], one_time_events: ['slug'],
  event_occurrences: ['recurring_event_id', 'start_datetime'],
}

/**
 * Characters that look like a space or nothing (non-breaking space, zero-width
 * and bidi marks, line separators). Written as JSON \u escapes so the SQL can be
 * copied by hand without silently changing a value (#101: 18 descriptions lost
 * their U+00A0 that way). Postgres parses the escape back to the same text.
 */
const INVISIBLE = new RegExp('[\\u00a0\\u00ad\\u1680\\u180e\\u2000-\\u200f\\u2028-\\u202f\\u205f-\\u206f\\u3000\\ufeff]', 'g')

function literal(value: unknown): string {
  const json = JSON.stringify(value).replace(INVISIBLE, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)
  if (json.includes(TAG)) throw new Error(`seed data contains the quote tag ${TAG}`)
  return `${TAG}${json}${TAG}::jsonb`
}

/** Upsert as drafts: a publishable table never gets published_at here (see publishSql). */
export function upsertSql(table: SeedTable, planned: Row[]): string {
  const rows = PUBLISH_AS[table] ? planned.map(r => Object.fromEntries(Object.entries(r).filter(([k]) => k !== 'published_at'))) : planned
  const keys = [...new Set(rows.flatMap(r => Object.keys(r)))]
  const bad = keys.find(k => !IDENT.test(k))
  if (bad) throw new Error(`${table}: unexpected column name ${bad}`)
  const fk = FOREIGN[table] ?? {}
  const plain = keys.filter(k => !(k in fk))
  const linked = Object.entries(fk).filter(([k]) => keys.includes(k))
  const columns = [...plain, ...linked.map(([, [c]]) => c)]
  const values = [
    ...plain.map(c => `r.${c}`),
    ...linked.map(([k, [, t]]) => `(select id from ${t} where slug = e->>'${k}')`),
  ]
  const updates = columns.filter(c => !CONFLICT[table].includes(c)).map(c => `${c} = excluded.${c}`)
  return [
    `insert into ${table} (${columns.join(', ')})`,
    `select ${values.join(', ')}`,
    `from jsonb_array_elements(${literal(rows)}) e, jsonb_populate_record(null::${table}, e) r`,
    `on conflict (${CONFLICT[table].join(', ')}) do update set ${updates.join(', ')};`,
  ].join('\n')
}

/**
 * Publishes each row that has a publish time, as the seed actor, unless its
 * publish state was already changed through cms_set_published (any
 * publication_events row): a re-run never overrides a staff unpublish. An
 * already published row keeps its time and records no event.
 */
export function publishSql(table: SeedTable, rows: Row[]): string | null {
  const type = PUBLISH_AS[table]
  const dated = rows.filter(r => r.published_at != null).map(r => ({ slug: r.slug, published_at: r.published_at }))
  if (!type || !dated.length) return null
  return [
    `select public.cms_set_published('${type}', t.id, true, (${SEED_ACTOR}), (e->>'published_at')::timestamptz)`,
    `from jsonb_array_elements(${literal(dated)}) e join ${table} t on t.slug = e->>'slug'`,
    `where not exists (select 1 from publication_events p where p.entity_type = '${type}' and p.entity_id = t.id);`,
  ].join('\n')
}

/**
 * Refuses inside the transaction without an active seed actor, or while a
 * planned event slug is published in the other event table (the public page
 * reads one-time events first).
 */
function preconditions(plan: SeedPlan): string {
  const slugs = (rows: Row[]) => literal(rows.map(r => r.slug))
  return [
    'do $guard$ begin',
    `  if not exists (${SEED_ACTOR}) then`,
    `    raise exception 'seed refused: no active seed system actor (apply 20261120000000_system_actors.sql first)';`,
    '  end if;',
    `  if exists (select 1 from one_time_events where published_at is not null and slug in (select jsonb_array_elements_text(${slugs(plan.recurring_events)})))`,
    `  or exists (select 1 from recurring_events where published_at is not null and slug in (select jsonb_array_elements_text(${slugs(plan.one_time_events)}))) then`,
    `    raise exception 'seed refused: a planned event slug is published in the other event table (run batch A first)';`,
    '  end if;',
    'end $guard$;',
  ].join('\n')
}

export function renderSeedSql(plan: SeedPlan, header: string): string {
  return [header.trim(), '', 'begin;', '', preconditions(plan), '',
    ...SEED_TABLES.flatMap(t => {
      const publish = publishSql(t, plan[t])
      return [`-- ${t}: ${plan[t].length} rows`, upsertSql(t, plan[t]), ...(publish ? [publish] : []), '']
    }),
    'commit;', ''].join('\n')
}
